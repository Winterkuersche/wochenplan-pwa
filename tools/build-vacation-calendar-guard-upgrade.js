// Offline packaging only. Applies no changes to any database.
const fs = require('node:fs');
function buildVacationCalendarGuardUpgrade() {
  const shared = fs.readFileSync('supabase/collaboration-schema.sql', 'utf8');
  const personal = fs.readFileSync('supabase/wochenplan-schema.sql', 'utf8');
  const start = shared.indexOf('create function wochenplan_private.api(');
  const end = shared.indexOf('end $$;', start);
  const api = shared.slice(start, end + 'end $$;'.length);
  const revision = personal.match(/create function public\.wochenplan_check_revision\(\)[\s\S]*?\n\$\$;/)?.[0];
  if (start < 0 || end < start || !revision) throw new Error('Incomplete calendar guard functions');
  return `-- Generated by tools/build-vacation-calendar-guard-upgrade.js.
-- Existing installations: protect additive calendar data from older clients.
-- No plans, requests, accounts, snapshots or history are modified.
begin;
set local lock_timeout='10s';
set local statement_timeout='45s';
lock table wochenplan_private.branches in exclusive mode;
lock table public.wochenplan_documents in share row exclusive mode;

${api.replace('create function', 'create or replace function')}

${revision.replace('create function', 'create or replace function')}
commit;
`;
}
if (require.main === module) fs.writeFileSync('supabase/vacation-calendar-guard-upgrade.sql', buildVacationCalendarGuardUpgrade());
module.exports = { buildVacationCalendarGuardUpgrade };

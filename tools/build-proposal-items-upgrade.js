// Offline build only: this tool never connects to a database.
const fs = require('node:fs');
function buildUpgrade() {
  const source = fs.readFileSync('supabase/collaboration-schema.sql', 'utf8');
  const functions = ['apply_changes', 'proposal_items', 'api'].map(name => {
    const start = source.indexOf(`create function wochenplan_private.${name}(`);
    if (start < 0) throw new Error(`Missing function: ${name}`);
    const end = source.indexOf('end $$;', start);
    if (end < 0) throw new Error(`Incomplete function: ${name}`);
    return source.slice(start, end + 'end $$;'.length).replace('create function', 'create or replace function');
  });
  return `-- Generated by tools/build-proposal-items-upgrade.js from the installation schema.
-- Existing installations only. No plans, accounts or history are deleted.
begin;
-- Acquire locks in the same order as the RPC, before replacing its behavior.
lock table wochenplan_private.branches in exclusive mode;
alter table wochenplan_private.proposals drop constraint proposals_status_check;
alter table wochenplan_private.proposals add constraint proposals_status_check
 check(status in ('pending','accepted','rejected','mixed'));

${functions.join('\n\n')}

update wochenplan_private.proposals set changes=wochenplan_private.proposal_items(changes) where status='pending';
revoke all on all functions in schema wochenplan_private from public,anon,authenticated;
grant execute on function wochenplan_private.api(text,jsonb) to authenticated;
commit;
`;
}
if (require.main === module) fs.writeFileSync('supabase/proposal-items-upgrade.sql', buildUpgrade());
module.exports = { buildUpgrade };
